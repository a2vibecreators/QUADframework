def run_doc(subcommand: str = None, args: List[str] = None):
    """Entry point for CLI integration"""
    args = args or []

    if subcommand == "init":
        init_documentation()

    elif subcommand == "generate":
        if not args:
            Console.error("Specify what to generate: api, db, arch, journey, all")
            return

        target = args[0]
        if target == "api":
            generate_api_docs()
        elif target == "db":
            generate_db_docs()
        elif target == "arch":
            generate_arch_docs()
        elif target == "journey":
            generate_test_journey()
        elif target == "all":
            generate_all_docs()
        else:
            Console.error(f"Unknown target: {target}")

    elif subcommand == "validate":
        validate_docs()

    elif subcommand == "config":
        if args and args[0] == "show":
            show_config()
        else:
            show_config()

    else:
        Console.header("QUAD Documentation Commands")
        Console.info("quad doc init                 - Initialize doc structure")
        Console.info("quad doc generate arch        - Generate architecture docs")
        Console.info("quad doc generate api         - Generate API docs")
        Console.info("quad doc generate db          - Generate DB docs")
        Console.info("quad doc generate journey     - Generate test journey")
        Console.info("quad doc generate all         - Generate all docs")
        Console.info("quad doc validate             - Validate doc structure")
        Console.info("quad doc config show          - Show doc config")
        print()


def main():
    """Command-line entry point"""
    args = sys.argv[1:]

    if not args or args[0] in ("-h", "--help"):
        run_doc("help")
    else:
        run_doc(args[0], args[1:])


if __name__ == "__main__":
    main()
