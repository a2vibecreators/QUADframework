def validate_docs():
    """Validate documentation structure"""
    Console.header("Validate Documentation")

    config = load_doc_config()
    project_root = find_project_root() or Path.cwd()

    checks_passed = 0
    checks_failed = 0

    # Check 1: Documentation root exists
    doc_root = project_root / config["documentation_root"]
    if doc_root.exists():
        Console.success(f"Documentation root exists: {config['documentation_root']}/")
        checks_passed += 1
    else:
        Console.error(f"Documentation root missing: {config['documentation_root']}/")
        checks_failed += 1

    # Check 2: Required folders exist
    for category, path in config.get("structure", {}).items():
        full_path = project_root / path
        if full_path.exists():
            checks_passed += 1

            # Check for README.md
            readme_path = full_path / "README.md"
            if readme_path.exists():
                checks_passed += 1
            else:
                Console.warn(f"Missing README.md in: {path}/")
                checks_failed += 1
        else:
            Console.error(f"Missing folder: {path}/")
            checks_failed += 1

    # Summary
    print()
    total = checks_passed + checks_failed
    score = int((checks_passed / total) * 100) if total > 0 else 0

    if score == 100:
        Console.success(f"All checks passed! Score: {score}%")
    elif score >= 80:
        Console.info(f"Most checks passed. Score: {score}%")
    else:
        Console.warn(f"Several checks failed. Score: {score}%")

    print()
    Console.info(f"Passed: {checks_passed}/{total}")
    Console.info(f"Failed: {checks_failed}/{total}")


