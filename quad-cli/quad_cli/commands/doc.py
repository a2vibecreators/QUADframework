class Console:
    """Simple console utilities"""

    @staticmethod
    def header(text: str):
        print(f"\n  {text}")
        print(f"  {'─' * len(text)}\n")

    @staticmethod
    def success(text: str):
        print(f"  ✓ {text}")

    @staticmethod
    def info(text: str):
        print(f"  → {text}")

    @staticmethod
    def error(text: str):
        print(f"  ✗ {text}")

    @staticmethod
    def warn(text: str):
        print(f"  ⚠ {text}")


def find_project_root() -> Optional[Path]:
    """Find project root by looking for .quad/ folder"""
    cwd = Path.cwd()
    for parent in [cwd] + list(cwd.parents):
        quad_dir = parent / ".quad"
        if quad_dir.exists():
            return parent
    return None


def load_doc_config() -> Dict:
    """Load documentation configuration"""
    # Check project-level config first
    project_root = find_project_root()
    if project_root:
        config_file = project_root / ".quad" / "doc-config.json"
        if config_file.exists():
            return json.loads(config_file.read_text())

    # Check QUAD framework config
    quad_root = Path(__file__).parent.parent.parent.parent
    config_file = quad_root / ".quad" / "doc-config.json"
    if config_file.exists():
        return json.loads(config_file.read_text())

    # Default config
    return {
        "documentation_root": "documentation",
        "structure": {
            "architecture": "documentation/architecture",
            "api": "documentation/api",
            "database": "documentation/database",
            "testing": "documentation/testing",
            "deployment": "documentation/deployment",
            "security": "documentation/security",
            "misc": "documentation/misc"
        }
    }


def get_doc_path(category: str) -> Path:
    """Get documentation path for category"""
    config = load_doc_config()
    project_root = find_project_root() or Path.cwd()

    category_path = config.get("structure", {}).get(
        category,
        f"{config['documentation_root']}/{category}"
    )

    return project_root / category_path


def init_documentation():
    """Initialize documentation structure"""
    Console.header("Initialize Documentation Structure")

    config = load_doc_config()
    project_root = find_project_root() or Path.cwd()

    Console.info(f"Project: {project_root.name}")

    # Create all category folders
    created = 0
    for category, path in config.get("structure", {}).items():
        full_path = project_root / path
        if not full_path.exists():
            full_path.mkdir(parents=True, exist_ok=True)

            # Create README.md in each folder
            readme_path = full_path / "README.md"
            readme_content = f"""# {category.title()} Documentation

## Overview

{category.title()} documentation for {project_root.name}.

## Contents

*Documentation files will appear here as they are generated.*

---

*Generated by QUAD on {datetime.now().strftime('%Y-%m-%d')}*
"""
            readme_path.write_text(readme_content)
            Console.success(f"Created: {path}/")
            created += 1

    # Create main documentation index
    doc_root = project_root / config["documentation_root"]
    index_path = doc_root / "README.md"

    if not index_path.exists():
        index_content = f"""# {project_root.name} Documentation

**Generated:** {datetime.now().strftime('%Y-%m-%d')}

---

## Documentation Categories

"""
        for category in config.get("structure", {}).keys():
            index_content += f"- [{category.title()}]({category}/README.md)\n"

        index_content += """
---

## Quick Links

- [Architecture Overview](architecture/README.md)
- [API Reference](api/README.md)
- [Database Schema](database/README.md)
- [Test Journeys](testing/README.md)

---

*Generated by QUAD*
"""
        index_path.write_text(index_content)
        Console.success("Created: documentation/README.md")
        created += 1

    print()
    if created > 0:
        Console.success(f"Documentation structure initialized! ({created} files created)")
    else:
        Console.info("Documentation structure already exists")


